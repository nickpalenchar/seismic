type Strings = typeof en;

function withExtensionStrings(core: Strings, language: Language): Strings {
  const extra: Record<string, unknown> = {};
  for (const extension of extensions) for (const [key, value] of Object.entries(extension.strings?.[language] ?? {})) {
    if (key in core || key in extra) throw new Error(`duplicate ${language} string: ${key}`);
    extra[key] = value;
  }
  return Object.keys(extra).length ? Object.assign({}, core, extra) : core;
}
const tables: Record<Language, Strings> = { en: withExtensionStrings(en, 'en') };
/** The strings in effect. */
export let t: Strings = tables.en;
/** The locale dates and numbers are written in. */
let locale = 'en-US';

/**
 * Puts `language` into effect, before the first render. Dates and numbers take the browser's
 * variant of it (`en-GB` writes the day first), or the usual one. A browser on Linux with the
 * POSIX locale says `en-US@posix`, which `Intl` refuses: the page stayed blank on it.
 */
export function setLanguage(language: Language, preferred: readonly string[] = typeof navigator === 'undefined' ? [] : navigator.languages) {
  t = tables[language];
  locale = preferred.find((l) => languageOf(l) === language && validTag(l)) ?? 'en-US';
  if (typeof document !== 'undefined') document.documentElement.lang = language;
}

function validTag(tag: string): boolean {
  try {
    return Intl.getCanonicalLocales(tag).length > 0;
  } catch {
    return false;
  }
}

/** The keys that paste, and that take a screenshot onto the clipboard where the system has one for it. */
export function pasteKeys(platform = typeof navigator !== 'undefined' ? navigator.platform : '') {
  if (/Mac/.test(platform)) return { paste: '⌘V', grab: '⌃⇧⌘4' };
  if (/Win/.test(platform)) return { paste: t.shots.ctrlV, grab: t.shots.winShiftS };
  return { paste: t.shots.ctrlV };
}

/** A file's size: bytes, KB or MB (as 1000s, like the systems' file managers mostly show them). */
export const fileSize = (bytes: number) => {
  const [n, unit] = bytes < 1000 ? [bytes, 'B'] : bytes < 1e6 ? [bytes / 1e3, 'KB'] : bytes < 1e9 ? [bytes / 1e6, 'MB'] : [bytes / 1e9, 'GB'];
  return `${n.toLocaleString(locale, { maximumFractionDigits: n < 10 ? 1 : 0 })} ${unit}`;
};
/** A time of day, hours and minutes. */
export const clock = (d: Date | string | number) => new Date(d).toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit' });
/** When a snoozed card wakes: "today, 18:00", "tomorrow, 08:00", else its weekday and date ("Sat 31 Oct, 08:00"), with the year when it is not this one. */
export const snoozeWhen = (at: string | number) => {
  const d = new Date(at);
  const now = new Date();
  const next = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1);
  const day =
    d.toDateString() === now.toDateString()
      ? t.snooze.today
      : d.toDateString() === next.toDateString()
        ? t.snooze.nextDay
        : d
            .toLocaleDateString(locale, { weekday: 'short', day: 'numeric', month: 'numeric', ...(d.getFullYear() === now.getFullYear() ? {} : { year: 'numeric' }) })
            .replace(/^(\p{L}+)\.?,?/u, '$1');
  return `${day}, ${clock(d)}`;
};
/** A short date: day and month. */
export const shortDay = (d: Date | string | number) => new Date(d).toLocaleDateString(locale, { day: 'numeric', month: 'short' });
/** A long date with its weekday; the year only when it is not this one. */
const longDay = (d: Date, today: Date) =>
  d.toLocaleDateString(locale, { weekday: 'long', day: 'numeric', month: 'long', ...(d.getFullYear() === today.getFullYear() ? {} : { year: 'numeric' }) });
/** A number, with `digits` decimals at most. */
const number = (n: number, digits = 0) => n.toLocaleString(locale, { maximumFractionDigits: digits, minimumFractionDigits: digits });

/** English ordinal: 2nd, 3rd, 11th. */
const ordinal = (n: number) => `${n}${['th', 'st', 'nd', 'rd'][n % 100 >= 11 && n % 100 <= 13 ? 0 : n % 10 < 4 ? n % 10 : 0]}`;

